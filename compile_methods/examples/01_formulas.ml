// Пример 1: проверка сложных формул с вводом значений
// и выводом результата.
//
// Вычисление: ((a + b) * c - d) / 2
//
read(a);
read(b);
read(c);
read(d);

x := ((a + b) * c - d) / 2;
write(x);

// Вычисление дискриминанта: D = b^2 - 4*a*c
read(qa);
read(qb);
read(qc);
d2 := qb * qb - 4 * qa * qc;
write(d2);
