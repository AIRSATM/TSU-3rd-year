// Пример 2: тест из задания — ввод n, ввод n элементов массива,
// упорядочение массива (сортировка пузырьком), вывод массива.

read(n);
array a[1000];

// читаем n элементов
i := 0;
while i < n do
    read(a[i]);
    i := i + 1
end;

// сортировка пузырьком по возрастанию
i := 0;
while i < n - 1 do
    j := 0;
    while j < n - 1 - i do
        if a[j] > a[j + 1] then
            t := a[j];
            a[j] := a[j + 1];
            a[j + 1] := t
        end;
        j := j + 1
    end;
    i := i + 1
end;

// выводим отсортированный массив
i := 0;
while i < n do
    write(a[i])
    i := i + 1
end;
