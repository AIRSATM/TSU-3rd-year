def barrett_mu(m, b, k=None):
    """
    Вычисляет константу μ = floor(b^(2k) / m) для алгоритма Барретта.
    Параметры:
      m – модуль (int)
      b – основание системы счисления
      k – число цифр модуля в системе по основанию b.
          Если не задано, вычисляется автоматически: 
          k = floor(log_b(m)) + 1.
    """
    if k is None:
        # Вычисляем количество цифр модуля в системе с основанием b
        k = 1
        power = b
        while power <= m:
            power *= b
            k += 1
    # mu = floor(b^(2k) / m)
    return (b ** (2 * k)) // m


def barrett_reduce(x, m, mu, b, k):
    """
    Вычисляет x mod m алгоритмом Барретта.
    Обязательное условие: 0 <= x < b^(2k).
    
    Параметры:
      x – число, которое нужно привести по модулю
      m – модуль (m >= 1)
      mu – предвычисленная константа floor(b^(2k) / m)
      b – основание системы счисления
      k – количество цифр модуля в данной системе
    
    Возвращает: r = x mod m, 0 <= r < m.
    """
    if m == 1:
        return 0  # всё делится на 1

    # Шаг 1: приближенное частное q = floor( floor(x / b^(k-1)) * mu / b^(k+1) )
    q = ((x // (b ** (k - 1))) * mu) // (b ** (k + 1))

    # Шаг 2: вычисляем остаток r = x - q * m (по модулю b^(k+1) для эффективности, но здесь мы просто вычитаем)
    r = x - q * m

    # Шаг 3: коррекция – r может быть немного больше или меньше m, 
    # но не более чем на 2m (теоретически). Вычитаем/прибавляем m пока не войдём в [0, m-1].
    while r >= m:
        r -= m
    while r < 0:
        r += m

    return r


