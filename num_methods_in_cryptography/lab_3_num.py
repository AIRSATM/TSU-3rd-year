# Пример использования
if __name__ == "__main__":
    # Тест 1: десятичная система, как в вашем примере
    b = 10
    x = 123456789
    m = 9999
    k = len(str(m))          # m состоит из 4 цифр -> k=4
    mu = barrett_mu(m, b, k)

    r = barrett_reduce(x, m, mu, b, k)
    print(f"Основание: {b}, k={k}")
    print(f"{x} mod {m} = {r} (встроенный % даёт {x % m})")

    # Тест 2: система по основанию 2^16 (более приближена к реальной машинной арифметике)
    b = 1 << 16   # 65536
    m = 10**9 + 7
    # Вычислим k – количество "цифр" (16-битных слов) в модуле
    tmp = m
    k = 0
    while tmp > 0:
        tmp //= b
        k += 1

    mu = barrett_mu(m, b, k)
    x = 9876543210123456789
    # Убедимся, что x < b^(2k)
    assert x < b ** (2 * k), "Число x должно быть короче 2k разрядов"

    r = barrett_reduce(x, m, mu, b, k)
    print(f"Основание: 2^16, k={k}")
    print(f"{x} mod {m} = {r} (встроенный % даёт {x % m})")