# ──── Глобальные настройки ──────────────────────────────────
set.seed(42)          # воспроизводимость
N     <- 100          # объём каждой выборки
ALPHA <- 0.05         # уровень значимости для всех тестов

# ─────────────────────────────────────────────────────────────
#  ЗАДАНИЕ 1.  Параметры и генерация выборок
# ─────────────────────────────────────────────────────────────
#
#  Ситуация (a): обе выборки из одного распределения.
#                Все тесты должны НЕ отвергнуть H₀.
#
#  Ситуация (b): средние отличаются сильно (Δμ = 7σ), дисп. равны.
#                F-тест не отвергнет H₀; t-тест уверенно отвергнет.
#
#  Ситуация (c): средние одинаковы, дисперсии различаются в 25 раз.
#                F-тест отвергнет H₀; t-тест (Уэлча) не отвергнет.
#
#  Ситуация (d): оба параметра различны.
#                Оба теста (F и t) должны отвергнуть H₀.
#
situations <- list(
  list(id = "a",
       label  = "(a)  μ₁=μ₂,  σ₁=σ₂",
       theory = "X1 ~ N(5, 2²)   X2 ~ N(5, 2²)",
       note   = "МО и дисперсии равны — H₀ ожидаем НЕ отвергать",
       mu1 = 5, sd1 = 2,
       mu2 = 5, sd2 = 2),

  list(id = "b",
       label  = "(b)  μ₁≠μ₂,  σ₁=σ₂",
       theory = "X1 ~ N(5, 2²)   X2 ~ N(19, 2²)",
       note   = "МО существенно различны, дисперсии равны — t-тест отвергнет",
       mu1 = 5,  sd1 = 2,
       mu2 = 19, sd2 = 2),

  list(id = "c",
       label  = "(c)  μ₁=μ₂,  σ₁≠σ₂",
       theory = "X1 ~ N(5, 1²)   X2 ~ N(5, 5²)",
       note   = "МО равны, дисперсии различны — F-тест отвергнет",
       mu1 = 5, sd1 = 1,
       mu2 = 5, sd2 = 5),

  list(id = "d",
       label  = "(d)  μ₁≠μ₂,  σ₁≠σ₂",
       theory = "X1 ~ N(5, 1²)   X2 ~ N(19, 5²)",
       note   = "МО и дисперсии различны — оба теста отвергнут",
       mu1 = 5,  sd1 = 1,
       mu2 = 19, sd2 = 5)
)

# Добавляем сгенерированные выборки прямо в каждый элемент списка
situations <- lapply(situations, function(s) {
  s$x1 <- rnorm(N, mean = s$mu1, sd = s$sd1)
  s$x2 <- rnorm(N, mean = s$mu2, sd = s$sd2)
  s
})

