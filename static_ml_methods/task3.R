cat(sprintf("N = %d на группу   |   уровень значимости α = %.2f\n\n", N, ALPHA))


# ─────────────────────────────────────────────────────────────
#  ЗАДАНИЕ 2a.  Функция статистических тестов
# ─────────────────────────────────────────────────────────────
#
#  Логика выбора теста:
#   1. Шапиро-Уилк: проверяем нормальность X1 и X2 по отдельности.
#   2. F-тест Фишера: проверяем равенство дисперсий.
#      Статистика F = s₁²/s₂² ~ F(n₁-1, n₂-1) при H₀: σ₁² = σ₂².
#   3. T-тест: проверяем равенство средних.
#      ВАЖНО: выбор версии теста зависит от результата шага 2:
#      • p(F-тест) > α  →  классический t-тест (var.equal=TRUE);
#        статистика t = (x̄₁-x̄₂) / [Sp · √(1/n₁ + 1/n₂)],
#        где Sp² = объединённая оценка дисперсии, df = n₁+n₂-2.
#      • p(F-тест) ≤ α  →  тест Уэлча (var.equal=FALSE);
#        не требует равенства дисперсий, df — по Саттертуэйту.
#
run_tests <- function(s, alpha = ALPHA) {
  x1 <- s$x1;  x2 <- s$x2

  div <- strrep("═", 66)
  cat(sprintf("\n%s\n", div))
  cat(sprintf("  Ситуация %s\n  %s\n  → %s\n",
              s$label, s$theory, s$note))
  cat(sprintf("%s\n", strrep("─", 66)))

  # ── Описательные статистики ──────────────────────────────
  cat("\n  Описательные статистики:\n")
  cat(sprintf("    X1:  x̄=%7.4f   s²=%7.4f   s=%7.4f   min=%6.3f   max=%6.3f\n",
              mean(x1), var(x1), sd(x1), min(x1), max(x1)))
  cat(sprintf("    X2:  x̄=%7.4f   s²=%7.4f   s=%7.4f   min=%6.3f   max=%6.3f\n\n",
              mean(x2), var(x2), sd(x2), min(x2), max(x2)))

  # ── Тест Шапиро-Уилка ─────────────────────────────────────
  # H₀: данные нормально распределены.
  # W ∈ (0, 1]; W → 1 означает нормальность.
  # Малое p-value означает отклонение от нормальности.
  # Ограничение: работает при n ≤ 5000 (здесь n=100 — ОК).
  sw1 <- shapiro.test(x1)
  sw2 <- shapiro.test(x2)

  cat("  [1] Тест Шапиро-Уилка  (H₀: нормальность распределения):\n")
  cat(sprintf("      X1:  W=%.5f,  p=%.4f  →  %s H₀\n",
              sw1$statistic, sw1$p.value,
              ifelse(sw1$p.value > alpha, "Не отвергаем", "ОТВЕРГАЕМ ")))
  cat(sprintf("      X2:  W=%.5f,  p=%.4f  →  %s H₀\n\n",
              sw2$statistic, sw2$p.value,
              ifelse(sw2$p.value > alpha, "Не отвергаем", "ОТВЕРГАЕМ ")))

  # ── F-тест Фишера на равенство дисперсий ─────────────────
  ftest  <- var.test(x1, x2)
  var_eq <- ftest$p.value > alpha   # логический флаг для t-теста

  cat("  [2] F-тест Фишера  (H₀: σ₁² = σ₂²):\n")
  cat(sprintf("      F=%.4f,  df=(%d, %d),  p=%.4f  →  %s H₀\n",
              ftest$statistic, ftest$parameter[1], ftest$parameter[2],
              ftest$p.value,
              ifelse(var_eq, "Не отвергаем", "ОТВЕРГАЕМ ")))
  cat(sprintf("      95%% ДИ для σ₁²/σ₂²: (%.4f; %.4f)\n",
              ftest$conf.int[1], ftest$conf.int[2]))
  cat(sprintf("      Вывод: дисперсии %s.\n\n",
              ifelse(var_eq, "статистически равны", "статистически различны")))

  # ── T-тест на равенство средних ──────────────────────────
  tt   <- t.test(x1, x2, var.equal = var_eq)
  meth <- ifelse(var_eq,
    "классический двухвыборочный t-тест (var.equal=TRUE)",
    "t-тест Уэлча (var.equal=FALSE, df по Саттертуэйту)")

  cat(sprintf("  [3] %s\n", meth))
  cat(sprintf("      H₀: μ₁ = μ₂   vs.   H₁: μ₁ ≠ μ₂\n"))
  cat(sprintf("      t=%.4f,  df=%.2f,  p=%.4f  →  %s H₀\n",
              tt$statistic, tt$parameter, tt$p.value,
              ifelse(tt$p.value > alpha, "Не отвергаем", "ОТВЕРГАЕМ ")))
  cat(sprintf("      95%% ДИ для (μ₁−μ₂): (%.4f; %.4f)\n\n",
              tt$conf.int[1], tt$conf.int[2]))

  invisible(list(sw1 = sw1, sw2 = sw2, ftest = ftest, ttest = tt))
}


# ─────────────────────────────────────────────────────────────
#  ЗАДАНИЕ 2b.  Гистограммы + KDE + вертикальные средние
# ─────────────────────────────────────────────────────────────
#
#  Техническая сложность: обе гистограммы строятся с одними и теми же
#  разбивками (breaks) — иначе полупрозрачные прямоугольники не будут
#  корректно перекрываться. Диапазон разбивок берём по объединению данных.
#  KDE (kernel density estimate) строится через density() — это
#  непараметрическая оценка плотности, которая сглаживает гистограмму.
#
plot_hist_density <- function(s) {
  x1 <- s$x1;  x2 <- s$x2

  # Полупрозрачные цвета: rgb(R, G, B, alpha) где alpha ∈ [0,1]
  COL1  <- rgb(0.22, 0.45, 0.78, 0.50)   # синий, 50% прозрачность
  COL2  <- rgb(0.75, 0.18, 0.18, 0.45)   # красный, 45% прозрачность
  LINE1 <- "steelblue"
  LINE2 <- "firebrick"

  all_data <- c(x1, x2)
  rng      <- range(all_data)
  x_pad    <- diff(rng) * 0.10

  # Единые разбивки для обеих гистограмм — корректное визуальное наложение
  n_bins <- max(nclass.Sturges(all_data), 15)
  breaks <- seq(rng[1], rng[2], length.out = n_bins + 1)

  # Вычисляем гистограммы и KDE без отрисовки (plot=FALSE)
  h1 <- hist(x1, breaks = breaks, plot = FALSE)
  h2 <- hist(x2, breaks = breaks, plot = FALSE)
  d1 <- density(x1)   # ядерная оценка плотности (полоса пропускания — авто)
  d2 <- density(x2)

  # Максимум оси Y с запасом 20%
  y_max <- max(h1$density, h2$density, d1$y, d2$y) * 1.20

  # ── Гистограмма X1 (она же задаёт систему координат) ─────
  plot(h1, freq = FALSE,
       col    = COL1,
       border = NA,
       xlim   = c(rng[1] - x_pad, rng[2] + x_pad),
       ylim   = c(0, y_max),
       main   = s$label,
       xlab   = "x",
       ylab   = "Плотность",
       cex.main = 0.92)

  # ── Гистограмма X2 (накладывается поверх) ────────────────
  plot(h2, freq = FALSE, col = COL2, border = NA, add = TRUE)

  # ── Ядерные оценки плотности ─────────────────────────────
  lines(d1, col = LINE1, lwd = 2.5)
  lines(d2, col = LINE2, lwd = 2.5)

  # ── Вертикальные линии средних значений ──────────────────
  abline(v = mean(x1), col = LINE1, lty = 2, lwd = 1.8)
  abline(v = mean(x2), col = LINE2, lty = 2, lwd = 1.8)

  # ── Легенда ──────────────────────────────────────────────
  legend("topright",
         legend = c(sprintf("X1  x̄=%.2f,  s=%.2f", mean(x1), sd(x1)),
                    sprintf("X2  x̄=%.2f,  s=%.2f", mean(x2), sd(x2))),
         col    = c(LINE1, LINE2),
         pch    = 22,
         pt.bg  = c(COL1, COL2),
         pt.cex = 1.9,
         lwd    = 2.3,
         cex    = 0.80,
         bty    = "n")
}


# ─────────────────────────────────────────────────────────────
#  ЗАДАНИЕ 2c.  Коробки с усами (boxplot)
# ─────────────────────────────────────────────────────────────
#
#  Анатомия boxplot:
#   • Нижний ус   = max(min(x), Q1 − 1.5·IQR)
#   • Нижняя грань ящика = Q1 (25-й перцентиль)
#   • Центральная линия  = медиана (Q2)
#   • Верхняя грань ящика = Q3 (75-й перцентиль)
#   • Верхний ус   = min(max(x), Q3 + 1.5·IQR)
#   • Точки за усами = выбросы (отмечаются автоматически)
#
#  Ромб ◇ на графике — выборочное среднее x̄ (может не совпадать
#  с медианой, если распределение несимметрично или есть выбросы).
#
plot_boxplots <- function(s) {
  x1 <- s$x1;  x2 <- s$x2

  COL1 <- rgb(0.22, 0.45, 0.78, 0.50)
  COL2 <- rgb(0.75, 0.18, 0.18, 0.45)

  boxplot(
    list(X1 = x1, X2 = x2),
    col     = c(COL1, COL2),
    border  = c("steelblue", "firebrick"),
    notch   = FALSE,      # TRUE добавит выемки ≈ 95% ДИ для медианы
    outline = TRUE,       # показываем выбросы точками
    main    = s$label,
    ylab    = "x",
    xlab    = "",
    cex.main = 0.92
  )

  # Ромб для выборочного среднего: отличается от медианы при асимметрии
  points(1, mean(x1), pch = 23, bg = "white",
         col = "steelblue", cex = 1.6, lwd = 2)
  points(2, mean(x2), pch = 23, bg = "white",
         col = "firebrick", cex = 1.6, lwd = 2)

  legend("topright",
         legend = c(sprintf("X1  x̄=%.2f,  med=%.2f,  s=%.2f",
                            mean(x1), median(x1), sd(x1)),
                    sprintf("X2  x̄=%.2f,  med=%.2f,  s=%.2f",
                            mean(x2), median(x2), sd(x2)),
                    "◇  выборочное среднее"),
         col    = c("steelblue", "firebrick", "grey40"),
         pch    = c(22, 22, 23),
         pt.bg  = c(COL1, COL2, "white"),
         pt.cex = c(1.8, 1.8, 1.4),
         cex    = 0.78,
         bty    = "n")
}


