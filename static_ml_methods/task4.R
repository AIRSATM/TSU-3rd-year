# ─────────────────────────────────────────────────────────────
#  ЗАДАНИЕ 4: Диаграммы рассеяния
# ─────────────────────────────────────────────────────────────
#
# Для каждой пары рисуем:
#  • облако точек (scatter plot);
#  • линию регрессии Y ~ X (МНК);
#  • 95% доверительный эллипс рассеяния.
#
# Доверительный эллипс: множество точек, для которых
#   (p − μ)ᵀ Σ⁻¹ (p − μ) ≤ χ²_{0.95, 2} ≈ 5.991
# Геометрически — эллипс с полуосями √(χ²·λᵢ) вдоль
# собственных векторов ковариационной матрицы Σ.
# При сильной корреляции эллипс вытянут вдоль главной диагонали.
#
add_ellipse <- function(x, y, conf = 0.95, ...) {
  Sigma  <- cov(cbind(x, y))          # 2×2 ковариационная матрица
  center <- c(mean(x), mean(y))
  eig    <- eigen(Sigma)               # λ₁≥λ₂; V=[v₁,v₂]
  cval   <- qchisq(conf, df = 2)      # χ²_{0.95,2} ≈ 5.991

  # Параметрически: p − μ = [cos θ, sin θ] · diag(√(χ²·λ)) · Vᵀ
  theta <- seq(0, 2 * pi, length.out = 300)
  ell   <- cbind(cos(theta), sin(theta)) %*%
           diag(sqrt(cval * eig$values)) %*%
           t(eig$vectors)

  lines(ell[, 1] + center[1], ell[, 2] + center[2], ...)
}

plot_scatter <- function(x, y, label_x, label_y, r_hat, r_theory) {
  C1 <- rgb(0.22, 0.45, 0.78, 0.50)   # полупрозрачный синий

  plot(x, y,
       main = sprintf("%s и %s   (ρ теор=%.2f,  r̂=%.4f)",
                      label_x, label_y, r_theory, r_hat),
       xlab = label_x, ylab = label_y,
       col  = C1, pch = 20, cex = 0.85, cex.main = 0.90)

  # Линия регрессии по МНК: y = b0 + b1·x
  m  <- lm(y ~ x)
  abline(m, col = "firebrick", lwd = 2.2)

  # 95% доверительный эллипс
  add_ellipse(x, y, conf = 0.95,
              col = "grey40", lwd = 1.5, lty = 2)

  # Аннотация: уравнение регрессии
  b0 <- coef(m)[1];  b1 <- coef(m)[2]
  legend("topleft",
         legend = c(sprintf("ρ теор = %.2f",  r_theory),
                    sprintf("r̂ выб  = %.4f", r_hat),
                    sprintf("y = %.2f + %.2f·x", b0, b1),
                    "95% эллипс"),
         col    = c(NA, NA, "firebrick", "grey40"),
         lty    = c(NA, NA, 1, 2),
         lwd    = c(NA, NA, 2.2, 1.5),
         text.col = c("grey25", "steelblue", "firebrick", "grey40"),
         cex    = 0.82, bty = "n")
}

