# ──── Глобальные настройки ───────────────────────────────────
set.seed(42)
N     <- 200    # объём каждой выборки
alpha <- 0.05   # уровень значимости

# ──── Задание 1: параметры X1 (задаём произвольно) ───────────
a1 <- 5 ;  S1 <- 2   # X1 ~ N(5, 2²)

# ──── Задание 2: целевые коэффициенты корреляции ─────────────
r1 <- 0.15   # слабая корреляция,  r1 ∈ [0.1; 0.2]
r2 <- 0.75   # сильная корреляция, r2 ∈ [0.6; 0.9]

# Параметры шумовой компоненты.
# КЛЮЧЕВОЕ УСЛОВИЕ: S2 = S1 — только тогда формула из задания
# обеспечивает теоретическую корреляцию ровно r1 или r2.
#
# Доказательство (при S2 = S1 = S):
#   X2 = r1·X1 + √(1−r1²)·ε,  ε ~ N(a2, S)
#   Var(X2) = r1²·S² + (1−r1²)·S² = S²
#   Cov(X1, X2) = r1·Var(X1) = r1·S²     [X1 и ε независимы]
#   Cor(X1, X2) = r1·S² / (S·S) = r1  ✓
#
# При S2 ≠ S1 теор. корреляция была бы:
#   r1·S1 / √(r1²·S1² + (1−r1²)·S2²) ≠ r1
#
a2 <- 3 ;  S2 <- S1   # S2 = S1 гарантирует cor(X1,X2) = r1

cat("\n╔═══════════════════════════════════════════════════════════╗\n")
cat(  "║    ЛАБ. РАБОТА №4 — КОРРЕЛИРОВАННЫЕ ВЫБОРКИ              ║\n")
cat(  "╚═══════════════════════════════════════════════════════════╝\n")
cat(sprintf("  N = %d  |  α = %.2f\n", N, alpha))
cat(sprintf("  X1 ~ N(a1=%g, S1=%g)   |   шум ~ N(a2=%g, S2=%g)\n",
            a1, S1, a2, S2))
cat(sprintf("  Целевые корреляции: ρ₁ = %.2f  ρ₂ = %.2f\n\n", r1, r2))


# ─────────────────────────────────────────────────────────────
#  ЗАДАНИЕ 1: Генерация X1
# ─────────────────────────────────────────────────────────────
X1 <- rnorm(N, mean = a1, sd = S1)


# ─────────────────────────────────────────────────────────────
#  ЗАДАНИЕ 3: Генерация X2 и X3 с заданными корреляциями
# ─────────────────────────────────────────────────────────────
# Метод: представить Xᵢ как линейную комбинацию X1 и независимого шума.
# Вес r при X1 → "доля объяснённой дисперсии".
# Вес √(1−r²) при шуме → нормировка, чтобы Var(Xᵢ) = Var(X1).
X2 <- r1 * X1 + sqrt(1 - r1^2) * rnorm(N, a2, S2)   # cor(X1,X2) ≈ r1
X3 <- r2 * X1 + sqrt(1 - r2^2) * rnorm(N, a2, S2)   # cor(X1,X3) ≈ r2


# ─────────────────────────────────────────────────────────────
#  ЗАДАНИЕ 5: Выборочные парные коэффициенты корреляции
# ─────────────────────────────────────────────────────────────
# Коэффициент Пирсона:
#   r̂ = Σ(xᵢ−x̄)(yᵢ−ȳ) / √[Σ(xᵢ−x̄)² · Σ(yᵢ−ȳ)²]
# Измеряет силу и направление линейной связи, r̂ ∈ [−1; 1].
r_hat1 <- cor(X1, X2)
r_hat2 <- cor(X1, X3)

cat("────────────────────────────────────────────────────────────\n")
cat("  Задание 5: Выборочные коэффициенты корреляции Пирсона\n")
cat("────────────────────────────────────────────────────────────\n")
cat(sprintf("  X1 и X2:  ρ₁ теор = %.2f   r̂₁ = %.4f   Δ = %.4f\n",
            r1, r_hat1, abs(r_hat1 - r1)))
cat(sprintf("  X1 и X3:  ρ₂ теор = %.2f   r̂₂ = %.4f   Δ = %.4f\n\n",
            r2, r_hat2, abs(r_hat2 - r2)))


# ─────────────────────────────────────────────────────────────
#  ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ: задания 6 и 7 для одной пары
# ─────────────────────────────────────────────────────────────
analyze_correlation <- function(x, y, label, r_theory, alpha = 0.05) {
  n <- length(x)
  r <- cor(x, y)   # выборочный коэффициент Пирсона

  # ── Задание 6: статистика Стьюдента ──────────────────────
  #
  # Гипотезы: H₀: ρ = 0  (линейная связь отсутствует)
  #           H₁: ρ ≠ 0  (линейная связь есть)
  #
  # Теорема: при H₀ статистика T = r̂·√(n−2)/√(1−r̂²) ~ t_{n−2}
  #
  # Откуда n−2? Из n наблюдений пары (X,Y) мы оцениваем 2 параметра:
  # μₓ и μᵧ — поэтому «тратим» 2 степени свободы.
  #
  # Физический смысл: чем дальше r̂ от нуля И чем больше n,
  # тем больше |T| → тем убедительнее свидетельство против H₀.
  #
  t_obs  <- r * sqrt(n - 2) / sqrt(1 - r^2)
  t_crit <- qt(1 - alpha/2, df = n - 2)
  p_val  <- 2 * pt(-abs(t_obs), df = n - 2)   # двусторонний p-value
  reject <- abs(t_obs) > t_crit

  # ── Задание 7: Z-преобразование Фишера ───────────────────
  #
  # Проблема прямого ДИ:
  #   Распределение r̂ сильно скошено при ρ ≠ 0 (особенно |ρ| → 1).
  #   Например, при ρ=0.9 и n=20 r̂ «прижат» сверху к 1 и правый хвост
  #   длиннее левого → симметричный ДИ вокруг r̂ будет неточным.
  #
  # Решение Фишера (1915):
  #   Z = arctanh(r̂) = ½·ln[(1+r̂)/(1−r̂)]
  #   Z ≈ N(arctanh(ρ),  1/(n−3))  —  дисперсия стабилизирована!
  #   При n=200: σ_Z = 1/√197 ≈ 0.071 — не зависит от ρ.
  #
  # Алгоритм:
  #   1. Вычислить Z = arctanh(r̂)
  #   2. Построить ДИ для Z: Z ± z_{α/2}/√(n−3)
  #   3. Обратное преобразование: ρ = tanh(Z_lower), tanh(Z_upper)
  #
  Z_hat  <- atanh(r)                   # atanh() — встроенная функция R
  Z_se   <- 1 / sqrt(n - 3)            # стандартная ошибка Z
  z_crit <- qnorm(1 - alpha/2)         # z_{0.975} ≈ 1.9600

  Z_lo   <- Z_hat - z_crit * Z_se      # нижняя граница Z
  Z_hi   <- Z_hat + z_crit * Z_se      # верхняя граница Z
  r_lo   <- tanh(Z_lo)                 # нижняя граница ρ
  r_hi   <- tanh(Z_hi)                 # верхняя граница ρ

  # ── Вывод в консоль ──────────────────────────────────────
  sep <- strrep("─", 62)
  cat(sprintf("\n%s\n  Пара: %s   |   теор. ρ = %.2f\n%s\n",
              sep, label, r_theory, sep))
  cat(sprintf("  Выборочный коэффициент корреляции:  r̂ = %.4f\n\n", r))

  cat("  [6] Критерий значимости корреляции (тест Стьюдента)\n")
  cat(sprintf("      H₀: ρ=0   H₁: ρ≠0   α=%.2f\n", alpha))
  cat(sprintf("      Формула: t = r̂·√(n-2) / √(1-r̂²)\n"))
  cat(sprintf("               = %.4f · √%d / √(1 - %.4f²)\n", r, n-2, r))
  cat(sprintf("      t_набл   = %.4f\n", t_obs))
  cat(sprintf("      t_крит   = t(α/2=%g, df=%d) = %.4f\n",
              alpha/2, n-2, t_crit))
  cat(sprintf("      p-value  = %.6f\n", p_val))
  cat(sprintf("      |t_набл|=%.4f  %s  t_крит=%.4f\n",
              abs(t_obs), ifelse(reject, ">  →  ОТВЕРГАЕМ H₀",
                                          "≤  →  Не отвергаем H₀"), t_crit))
  cat(sprintf("      Вывод: корреляция %s (α=%.2f)\n\n",
              ifelse(reject, "статистически ЗНАЧИМА", "не значима"), alpha))

  cat("  [7] Доверительный интервал (Z-преобразование Фишера)\n")
  cat(sprintf("      Z = arctanh(r̂) = arctanh(%.4f) = %.4f\n", r, Z_hat))
  cat(sprintf("      SE(Z) = 1/√(n-3) = 1/√%d = %.4f\n", n-3, Z_se))
  cat(sprintf("      z_крит = %.4f\n", z_crit))
  cat(sprintf("      Полуширина ДИ = %.4f · %.4f = %.4f\n",
              z_crit, Z_se, z_crit * Z_se))
  cat(sprintf("      ДИ для Z: [%.4f; %.4f]\n", Z_lo, Z_hi))
  cat(sprintf("      ДИ для ρ = tanh(Z): [%.4f; %.4f]\n", r_lo, r_hi))
  cat(sprintf("      Теор. ρ=%.2f %s 95%% ДИ\n\n",
              r_theory,
              ifelse(r_theory >= r_lo & r_theory <= r_hi,
                     "✓ попадает в", "✗ НЕ попадает в")))

  # Независимая проверка через встроенную функцию cor.test()
  # (она реализует тот же алгоритм — результаты должны совпадать)
  ct <- cor.test(x, y)
  cat(sprintf("  Проверка cor.test():  t=%.4f,  p=%.6f\n",
              as.numeric(ct$statistic), ct$p.value))
  cat(sprintf("  95%% ДИ cor.test():    [%.4f; %.4f]\n",
              ct$conf.int[1], ct$conf.int[2]))

  invisible(list(r=r, t=t_obs, p=p_val, ci=c(r_lo, r_hi)))
}


# ─────────────────────────────────────────────────────────────
#  ЗАДАНИЯ 6 И 7: Запуск анализа
# ─────────────────────────────────────────────────────────────
cat("════════════════════════════════════════════════════════════\n")
cat("  Задания 6–7: Тест Стьюдента и ДИ Фишера\n")
cat("════════════════════════════════════════════════════════════\n")
res1 <- analyze_correlation(X1, X2, "X1 и X2", r1, alpha)
res2 <- analyze_correlation(X1, X3, "X1 и X3", r2, alpha)

