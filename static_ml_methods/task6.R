# ==============================================================================
# Подготовка окружения
# ==============================================================================
# Установка необходимых пакетов (если они не установлены)
if (!require("lmtest")) install.packages("lmtest")
library(lmtest) # Для теста Бреуша-Пагана (bptest)

# ==============================================================================
# 1-2. Импорт данных и переименование столбцов
# ==============================================================================
# Загружаем данные. Файл содержит разделитель ";" и запятые в десятичных дробях.
# Параметр stringsAsFactors = TRUE сразу переведет текст (Тип, Мебель) в факторы.
df <- read.csv("flats R.csv", sep=";", dec=",", stringsAsFactors=TRUE, 
               fileEncoding = "windows-1251")

# 2. Переименовываем столбцы латиницей
colnames(df) <- c("type", "price", "floor", "total_floors", "area", "furniture")

# Проверим структуру
str(df)
head(df)

# ==============================================================================
# 3. Визуализация данных
# ==============================================================================
# Настраиваем окно графиков для вывода нескольких графиков сразу
par(mfrow=c(2, 2))

# Гистограммы для непрерывных переменных
hist(df$price, main="Гистограмма цены", xlab="Цена (price)", col="lightblue")
hist(df$area, main="Гистограмма площади", xlab="Площадь (area)", col="lightgreen")

# Диаграммы размаха (Boxplots) для выявления выбросов
boxplot(price ~ type, data=df, main="Цена от типа квартиры", col="coral")
boxplot(price ~ furniture, data=df, main="Цена от наличия мебели", col="plum")

# Сброс настроек графиков
par(mfrow=c(1, 1))

# ==============================================================================
# 4. Проверка взаимосвязей факторов
# ==============================================================================
# Построим матрицу диаграмм рассеяния для численных переменных
numeric_vars <- df[, c("price", "floor", "total_floors", "area")]
plot(numeric_vars, main="Матрица рассеяния численных признаков", col="darkblue")

# Корреляционная матрица для численных признаков
cor_matrix <- cor(numeric_vars, use="complete.obs")
print("Корреляционная матрица:")
print(cor_matrix)

# ==============================================================================
# 5-7. Построение парной модели регрессии и анализ остатков
# ==============================================================================
# 5. Модель регрессии цены от метража
model_simple <- lm(price ~ area, data=df)
print(summary(model_simple))

# 6. Проверка остатков на нормальность (Критерий Шапиро-Уилка)
cat("\n--- Проверка остатков на нормальность ---\n")
print(shapiro.test(resid(model_simple)))

# 7. Проверка на гетероскедастичность (Критерий Бреуша-Пагана)
cat("\n--- Проверка на гетероскедастичность (Тест Бреуша-Пагана) ---\n")
print(bptest(model_simple))
# Если p-value < 0.05, гетероскедастичность присутствует.

# ==============================================================================
# 8-11. Устранение гетероскедастичности и новые модели
# ==============================================================================
# Способ 1: Деление на значение фактора (Взвешенный МНК - WLS)
# Мы даем веса обратно пропорциональные площади (или квадрату площади)
model_wls <- lm(price ~ area, data=df, weights = 1/df$area)

# Способ 2: Логарифмирование зависимой переменной (чаще всего работает лучше)
model_log <- lm(log(price) ~ area, data=df)

# 9. Построена новая парная модель (выберем логарифмическую как основную для проверки)
print(summary(model_log))

# 10. Проверка остатков новой модели (model_log) на нормальность
cat("\n--- Нормальность остатков лог-модели ---\n")
print(shapiro.test(resid(model_log)))

# 11. Проверка остатков новой модели на гетероскедастичность
cat("\n--- Гетероскедастичность лог-модели ---\n")
print(bptest(model_log))

# ==============================================================================
# 12. Диаграмма рассеяния, линия регрессии и доверительные интервалы
# ==============================================================================
# Для исходной парной модели построим график
plot(df$area, df$price, main="Парная регрессия: Цена от Площади", 
     xlab="Площадь", ylab="Цена", pch=16, col="gray")

# Линия регрессии
abline(model_simple, col="red", lwd=2)

# Создаем вектор площадей для отрисовки интервалов
area_seq <- data.frame(area = seq(min(df$area, na.rm=T), max(df$area, na.rm=T), length.out=100))

# Доверительный интервал (для функции регрессии, т.е. математического ожидания)
conf_int <- predict(model_simple, newdata=area_seq, interval="confidence")
lines(area_seq$area, conf_int[,"lwr"], col="blue", lty=2, lwd=2)
lines(area_seq$area, conf_int[,"upr"], col="blue", lty=2, lwd=2)

# Интервал прогноза (для конкретных новых наблюдений)
pred_int <- predict(model_simple, newdata=area_seq, interval="prediction")
lines(area_seq$area, pred_int[,"lwr"], col="darkgreen", lty=3, lwd=2)
lines(area_seq$area, pred_int[,"upr"], col="darkgreen", lty=3, lwd=2)

legend("topleft", legend=c("Линия регрессии", "Дов. интервал (среднее)", "Инт. прогноза (индивид.)"),
       col=c("red", "blue", "darkgreen"), lty=c(1,2,3), lwd=2)

# ==============================================================================
# 13-14. Множественная регрессия и удаление незначимых факторов
# ==============================================================================
# 13. Модель множественной регрессии на все факторы
model_mult <- lm(price ~ type + floor + total_floors + area + furniture, data=df)
cat("\n--- Множественная модель (все факторы) ---\n")
print(summary(model_mult))

# 14. Удаление незначимых факторов
# Вы можете удалять их вручную (ориентируясь на Pr(>|t|) > 0.05), 
# либо использовать автоматический пошаговый алгоритм (step):
model_mult_opt <- step(model_mult, direction="backward")
cat("\n--- Оптимизированная множественная модель ---\n")
print(summary(model_mult_opt))

# Вывод (для отчета): факторы удалены, так как их p-value в тесте Стьюдента
# оказалось больше 0.05. Это означает, что их влияние на цену статистически
# не отличается от нуля при наличии остальных признаков в модели.

# ==============================================================================
# 15. Прогноз для «своей квартиры»
# ==============================================================================
# Создадим данные вымышленной (вашей) квартиры. 
# ВНИМАНИЕ: Значения факторов (type, furniture) должны строго совпадать 
# с теми, что есть в исходной базе.
my_flat <- data.frame(
  type = factor("студия", levels = levels(df$type)),
  floor = 5,
  total_floors = 9,
  area = 25,
  furniture = factor("есть", levels = levels(df$furniture))
)

# Прогнозируем цену по оптимизированной модели (включаем доверительный интервал)
my_price_pred <- predict(model_mult_opt, newdata=my_flat, interval="prediction")
cat("\n--- Прогноз для 'своей' квартиры ---\n")
print(my_price_pred)

# ==============================================================================
# 16-17. Анализ остатков множественной модели и устранение гетероскедастичности
# ==============================================================================
# 16. Анализ остатков
cat("\n--- Нормальность остатков (множественная) ---\n")
print(shapiro.test(resid(model_mult_opt)))

cat("\n--- Гетероскедастичность (множественная) ---\n")
print(bptest(model_mult_opt))

# 17. Устранение гетероскедастичности логарифмированием зависимой переменной
# Строим финальную модель, используя формулу оптимизированной модели, но с log(price)
formula_opt <- formula(model_mult_opt)
formula_log <- update(formula_opt, log(price) ~ .)

model_mult_log <- lm(formula_log, data=df)
cat("\n--- Множественная логарифмическая модель ---\n")
print(summary(model_mult_log))

# Проверка, помогло ли логарифмирование
cat("\n--- Гетероскедастичность (множ. логарифмическая) ---\n")
print(bptest(model_mult_log))